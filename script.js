function updateCartUI() {
  const cartCountEl = document.getElementById("cartCount");
  const cartItemsContainer = document.getElementById("cartItemsContainer");
  const subtotalEl = document.getElementById("subtotal");
  const totalEl = document.getElementById("total");
  const shippingEl = document.getElementById("shipping");
  const checkoutBtn = document.getElementById("checkoutBtn");
  const shippingBar = document.getElementById("shippingBar");
  const shippingText = document.getElementById("shippingText");
  const minimumOrderWarning = document.getElementById("minimumOrderWarning");

  const totalCount = cart.reduce((sum, item) => sum + item.quantity, 0);
  if (cartCountEl) cartCountEl.textContent = totalCount;

  if (cartItemsContainer) {
    if (cart.length === 0) {
      cartItemsContainer.innerHTML = `<p class="empty-cart-msg">${translations[currentLang].empty_cart}</p>`;
    } else {
      cartItemsContainer.innerHTML = "";
      cart.forEach((item, index) => {
        const itemEl = document.createElement("div");
        itemEl.className = "cart-item";
        itemEl.innerHTML = `
          <div class="cart-item-info">
            <span class="cart-item-name">${item.name}</span>
            <span class="cart-item-details">
              ${item.isOffer ? '' : translations[currentLang].size_label + ': ' + item.size + ' | '}
              ${item.isOffer ? translations[currentLang].offer_price_label + ': ' + item.basePrice + ' EGP' : translations[currentLang].base_price_label + ': ' + item.basePrice + ' EGP'}
            </span>
          </div>
          <div class="cart-item-controls">
            <button class="qty-btn" onclick="updateQuantity(${index}, -1)">-</button>
            <span class="qty-num">${item.quantity}</span>
            <button class="qty-btn" onclick="updateQuantity(${index}, 1)">+</button>
            <button class="delete-btn" onclick="removeCartItem(${index})"><i class="bi bi-trash"></i></button>
          </div>
        `;
        cartItemsContainer.appendChild(itemEl);
      });
    }
  }

  const subtotal = cart.reduce((sum, item) => sum + (item.basePrice * item.quantity), 0);
  const freeShippingThreshold = 500;
  const shipping = (subtotal >= freeShippingThreshold || subtotal === 0) ? 0 : 50;
  const total = subtotal + shipping;

  if (subtotalEl) subtotalEl.textContent = `${subtotal} EGP`;
  if (totalEl) totalEl.textContent = `${total} EGP`;

  if (shippingEl) {
    shippingEl.textContent = shipping === 0 ? `${translations[currentLang].free} ✓` : `${shipping} EGP`;
  }

  if (shippingBar && shippingText) {
    const percent = Math.min(100, (subtotal / freeShippingThreshold) * 100);
    shippingBar.style.width = `${percent}%`;

    if (subtotal >= freeShippingThreshold) {
      shippingText.textContent = translations[currentLang].free_shipping_success;
    } else {
      const remaining = freeShippingThreshold - subtotal;
      shippingText.textContent = translations[currentLang].free_shipping_remaining.replace("{amount}", remaining.toFixed(2));
    }
  }

  const minimumOrder = 100;
  const isAboveMinimum = subtotal >= minimumOrder || subtotal === 0;

  if (minimumOrderWarning) {
    minimumOrderWarning.style.display = (subtotal > 0 && subtotal < minimumOrder) ? "block" : "none";
  }

  if (checkoutBtn) {
    checkoutBtn.disabled = cart.length === 0 || !isAboveMinimum;
  }
}

function updateQuantity(index, change) {
  cart[index].quantity += change;
  if (cart[index].quantity <= 0) {
    cart.splice(index, 1);
  }
  localStorage.setItem('kitchen_cart', JSON.stringify(cart));
  updateCartUI();
}

function removeCartItem(index) {
  cart.splice(index, 1);
  localStorage.setItem('kitchen_cart', JSON.stringify(cart));
  updateCartUI();
}

